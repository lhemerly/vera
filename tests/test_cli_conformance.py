"""User-facing compiler gates and exact input boundaries."""

from pathlib import Path
import json

from vera.cli import main

UNSAFE = """module Unsafe;
table T capacity 2 { key id:id64<T>; col v:u8; }
invariant zero { forall k in T : eq(T[k].v,0); }
transition wrong(k:id64<T>) reads [] writes [T[k].v]
require live : table_exists(T,k);
body { table_set(T,k,v,1); commit; }
"""


def test_codegen_refuses_unproved_source(tmp_path, capsys):
    source = tmp_path / "unsafe.vera"
    source.write_text(UNSAFE)
    output = tmp_path / "unsafe.rs"
    assert main(["codegen", "rust", str(source), "--out", str(output)]) == 1
    assert not output.exists()
    captured = capsys.readouterr()
    assert "VIOLATION" in captured.err or "rejected" in captured.err.lower()


def test_run_refuses_unproved_source(tmp_path, capsys):
    source = tmp_path / "unsafe.vera"
    source.write_text(UNSAFE)
    setup = tmp_path / "setup.json"
    setup.write_text(json.dumps({"tables": {"T": [{"id": 2, "v": 0}]}}))
    assert (
        main(
            [
                "run",
                str(source),
                "--transition",
                "wrong",
                "--param",
                "k=2",
                "--setup",
                str(setup),
            ]
        )
        == 1
    )
    assert "COMMIT" not in capsys.readouterr().out


def test_bad_boolean_argument_is_rejected(tmp_path, capsys):
    source = tmp_path / "input.vera"
    source.write_text("""module Inputs;
    table T capacity 2 {key id:id64<T>;col v:bool;}
    transition save(flag:bool) reads [] writes [T[*].v]
    body {let %k:id64<T> = table_alloc(T,{v:flag});commit;}""")
    assert (
        main(["run", str(source), "--transition", "save", "--param", "flag=perhaps"])
        == 1
    )
    assert "COMMIT" not in capsys.readouterr().out


def test_source_stdout_contains_only_generated_code(tmp_path, capsys):
    source = tmp_path / "source.vera"
    source.write_text("""module Valid;
    table T capacity 2 {key id:id64<T>;col v:u64;}
    transition save(k:id64<T>) reads [T[k].v] writes []
    body {commit;}""")
    assert main(["codegen", "rust", str(source)]) == 0
    captured = capsys.readouterr()
    assert captured.out.startswith("// Generated by VERA")
    assert "[WARNING]" not in captured.out


def test_exact_decimal_input_and_invalid_setup_are_checked(tmp_path, capsys):
    source = tmp_path / "decimal.vera"
    source.write_text("""module DecimalInput;
    table T capacity 2 {key id:id64<T>;col v:dec128;}
    invariant positive {forall k in T:ge(T[k].v,0);}
    transition create(value:dec128) reads [] writes [T[*].v]
    require positive:ge(value,0);
    body {let %k:id64<T>=table_alloc(T,{v:value});commit;}""")
    assert (
        main(
            [
                "run",
                str(source),
                "--transition",
                "create",
                "--param",
                "value=1.000000000000000001",
            ]
        )
        == 0
    )
    assert "1000000000000000001" in capsys.readouterr().out
    bad = tmp_path / "invalid.json"
    bad.write_text(json.dumps({"tables": {"T": [{"id": 2, "v": -1}]}}))
    assert (
        main(
            [
                "run",
                str(source),
                "--transition",
                "create",
                "--param",
                "value=1.0",
                "--setup",
                str(bad),
            ]
        )
        == 1
    )
    assert "COMMIT" not in capsys.readouterr().out


def test_explicit_unverified_mode_is_available_for_counterexample_work(
    tmp_path, capsys
):
    source = tmp_path / "unsafe.vera"
    source.write_text(UNSAFE)
    output = tmp_path / "unsafe.rs"
    assert (
        main(
            [
                "codegen",
                "rust",
                str(source),
                "--out",
                str(output),
                "--unverified",
                "--no-main",
            ]
        )
        == 0
    )
    assert output.read_text().startswith("// Generated by VERA")
