"""Target B (OpenGL): AST -> GLSL 4.6 compute furnace.

The local GPU is an AMD Radeon RX 6600 XT (Mesa radeonsi, GL 4.6 core).  The
emitter produces a self-contained compute shader implementing the Section 7
design on a warp-interleaved sandbox:

  * every warp owns one sandbox; lane ``L``'s row for slot ``S`` lives at
    ``col[S * 32 + L]`` -- a warp's simultaneous row accesses are one coalesced
    transaction;
  * ``select`` / ``guard`` / ``table_set`` compile to ``selp`` / predication,
    so a warp never diverges;
  * each lane runs a deterministic xoshiro256** PRNG and a D-step trajectory;
  * global invariants are evaluated after every step.

The host is ``tools/furnace_host.c`` (EGL surfaceless, no window).
"""

from typing import Dict, List

from . import ast_nodes as A
from .semantic import Program
from .types import ScalarType

GLSL_TYPE = {
    "bool": "uint", "u8": "uint", "u16": "uint", "u32": "uint", "u64": "uint64_t",
    "i64": "int64_t", "dec64": "int64_t", "dec128": "int64_t", "sym32": "uint",
    "bytes32": "uint64_t", "id64": "uint64_t", "enum": "uint",
}


def _glsl_name(name: str) -> str:
    out = []
    for ch in name:
        out.append('v_' if ch == '%' else (ch if (ch.isalnum() or ch == '_') else '_'))
    text = ''.join(out)
    return text if text and not text[0].isdigit() else 'v' + text


def _glsl_type(ctype: ScalarType) -> str:
    return GLSL_TYPE.get(ctype.kind, "int64_t")


def _let_type(prog, stmt):
    from .semantic import _resolve_type_ref
    from .types import ScalarType
    return _resolve_type_ref(prog, stmt.type, "let") or ScalarType("i64", 64, 8)


class GlslGenerator:
    def __init__(self, prog: Program, fuzz_cap: int = 16, depth: int = 64):
        self.prog = prog
        self.fuzz_cap = fuzz_cap
        self.depth = depth
        self.lines: List[str] = []
        self.lane = "vera_lane"

    def w(self, text: str = "") -> None:
        self.lines.append(text)

    def emit(self) -> str:
        self.w("// Generated by VERA v1.1.0 -- OpenGL 4.6 fuzzing furnace (Target B).")
        self.w("#version 460 core")
        self.w("#extension GL_ARB_gpu_shader_int64 : enable")
        self.w()
        self.w("layout(local_size_x = 32) in;")
        self.w()
        self.w("layout(std430, binding = 0) buffer Output {")
        self.w("    uint violations;")
        self.w("    uint committed;")
        self.w("    uint pad0;")
        self.w("    uint pad1;")
        self.w("};")
        self.w()
        for tname, tinfo in self.prog.tables.items():
            up = tname.upper()
            self.w(f"const int CAP_{up} = {tinfo.layout.capacity};")
            self.w(f"const int KEY_BITS_{up} = {tinfo.layout.key_bits};")
            self.w(f"const int GEN_BITS_{up} = {tinfo.layout.generation_bits};")
        self.w(f"const int FUZZ_CAP = {self.fuzz_cap};")
        self.w(f"const int DEPTH = {self.depth};")
        self.w()
        # sandbox arrays
        for tname, tinfo in self.prog.tables.items():
            for c in tinfo.columns.values():
                self.w(f"shared {_glsl_type(c.type)} {tname}_{c.name}[FUZZ_CAP * 32];")
            self.w(f"shared uint {tname}_occ[FUZZ_CAP * 32];")
            self.w(f"shared uint {tname}_gen[FUZZ_CAP * 32];")
            for c in tinfo.columns.values():
                if c.tracked_sum:
                    self.w(f"shared {_glsl_type(c.type)} {tname}_agg_{c.name}[32];")
        self.w()
        self._emit_prng()
        self._emit_helpers()
        for tname, tinfo in self.prog.tables.items():
            self._emit_table_helpers(tname, tinfo)
        for tname in self.prog.transitions:
            self._emit_transition(tname)
        self._emit_invariants()
        self._emit_main()
        return "\n".join(self.lines) + "\n"

    def _enum_tags(self) -> Dict[str, int]:
        out: Dict[str, int] = {}
        for tinfo in self.prog.tables.values():
            for cinfo in tinfo.columns.values():
                if cinfo.type.kind == "enum":
                    for i, tag in enumerate(cinfo.type.enum_tags):
                        out[tag] = i
        return out

    # --- PRNG ----------------------------------------------------------
    def _emit_prng(self) -> None:
        self.w("uint64_t vera_rotl64(uint64_t x, int k) { return (x << k) | (x >> (64 - k)); }")
        self.w("uint64_t vera_s0, vera_s1, vera_s2, vera_s3;")
        self.w("uint64_t vera_rng_next() {")
        self.w("    uint64_t result = vera_rotl64(vera_s1 * 5ul, 7) * 9ul;")
        self.w("    uint64_t t = vera_s1 << 17;")
        self.w("    vera_s2 ^= vera_s0; vera_s3 ^= vera_s1; vera_s1 ^= vera_s2;")
        self.w("    vera_s0 ^= vera_s3; vera_s2 ^= t; vera_s3 = vera_rotl64(vera_s3, 45);")
        self.w("    return result;")
        self.w("}")
        self.w("void vera_rng_seed(uint64_t seed) {")
        self.w("    uint64_t z = seed;")
        self.w("    for (int i = 0; i < 4; ++i) {")
        self.w("        z += 0x9E3779B97F4A7C15ul;")
        self.w("        uint64_t y = z;")
        self.w("        y = (y ^ (y >> 30)) * 0xBF58476D1CE4E5B9ul;")
        self.w("        y = (y ^ (y >> 27)) * 0x94D049BB133111EBul;")
        self.w("        if (i == 0) vera_s0 = y ^ (y >> 31);")
        self.w("        else if (i == 1) vera_s1 = y ^ (y >> 31);")
        self.w("        else if (i == 2) vera_s2 = y ^ (y >> 31);")
        self.w("        else vera_s3 = y ^ (y >> 31);")
        self.w("    }")
        self.w("}")
        self.w()

    # --- helpers -------------------------------------------------------
    def _emit_helpers(self) -> None:
        self.w("int vera_slot_of(uint64_t key, int bits) { return int(key & uint64_t((1ul << bits) - 1ul)); }")
        self.w("bool vera_valid(uint occ, uint gen, uint64_t key, int kb, int gb) {")
        self.w("    return occ != 0u && gen == uint((key >> kb) & ((1ul << gb) - 1ul)) && (key >> (kb + gb)) == 0ul;")
        self.w("}")
        self.w()

    def _emit_table_helpers(self, tname: str, tinfo) -> None:
        up = tname.upper()
        kb = tinfo.layout.key_bits
        gb = tinfo.layout.generation_bits
        self.w(f"bool {tname}_exists(int lane, uint64_t key) {{")
        self.w(f"    int s = vera_slot_of(key, {kb});")
        self.w(f"    return vera_valid({tname}_occ[s * 32 + lane], {tname}_gen[s * 32 + lane], key, {kb}, {gb});")
        self.w(f"}}")
        for c in tinfo.columns.values():
            gt = _glsl_type(c.type)
            self.w(f"{gt} {tname}_get_{c.name}(int lane, uint64_t key) {{")
            self.w(f"    int s = vera_slot_of(key, {kb});")
            self.w(f"    return {tname}_{c.name}[s * 32 + lane];")
            self.w(f"}}")
            self.w(f"void {tname}_set_{c.name}(int lane, uint64_t key, {gt} v) {{")
            self.w(f"    int s = vera_slot_of(key, {kb});")
            self.w(f"    {tname}_{c.name}[s * 32 + lane] = v;")
            self.w(f"}}")
        self.w()

    # --- transitions ---------------------------------------------------
    def _emit_transition(self, tname: str) -> None:
        ti = self.prog.transitions[tname]
        params = ", ".join(f"{_glsl_type(ti.param_types[p.name])} {p.name}"
                           for p in ti.decl.params)
        self.w(f"bool transition_{tname}(int lane, {params}) {{")
        env: Dict[str, str] = {p.name: p.name for p in ti.decl.params}
        for rname, rexpr in ti.decl.requires:
            self.w(f"    if (!({self._expr(rexpr, env)})) {{ return false; }}")
        for stmt in ti.decl.body:
            self._stmt(stmt, env)
        self.w("    return true;")
        self.w("}")
        self.w()

    def _stmt(self, stmt: A.Stmt, env: Dict[str, str]) -> None:
        if isinstance(stmt, A.Let):
            if isinstance(stmt.value, A.Fold):
                self.w(f"    // fold_bounded<{stmt.value.n}>() unrolled")
                self.w(f"    {_glsl_type(_let_type(self.prog, stmt))} {_glsl_name(stmt.name)} = {self._expr(stmt.value.init, env)};")
                self.w(f"    for (int i = 0; i < {stmt.value.n}; ++i) {{")
                inner = dict(env)
                inner[stmt.value.index_name] = f"int64_t({i})"
                inner[stmt.value.acc_name] = _glsl_name(stmt.name)
                for s in stmt.value.body:
                    self._stmt(s, inner)
                self.w(f"        {_glsl_name(stmt.name)} = {self._expr(stmt.value.yield_expr, inner)};")
                self.w("    }")
            else:
                self.w(f"    {_glsl_type(_let_type(self.prog, stmt))} {_glsl_name(stmt.name)} = {self._expr(stmt.value, env)};")
            env[stmt.name] = _glsl_name(stmt.name)
        elif isinstance(stmt, A.Guard):
            self.w(f"    if (!({self._expr(stmt.cond, env)})) {{ return false; }}")
        elif isinstance(stmt, A.TableSet):
            self.w(f"    {stmt.table}_set_{stmt.column}(lane, {self._expr(stmt.key, env)}, "
                  f"{self._expr(stmt.value, env)});")
        elif isinstance(stmt, A.TableAlloc):
            args = ", ".join(self._expr(e, env) for _, e in stmt.fields)
            self.w(f"    uint64_t {_glsl_name(stmt.name)} = {stmt.table}_alloc(lane, {args});")
            env[stmt.name] = _glsl_name(stmt.name)
        elif isinstance(stmt, A.Emit):
            self.w(f"    // emit {stmt.effect}")
        elif isinstance(stmt, A.Commit):
            pass

    def _expr(self, expr: A.Expr, env: Dict[str, str]) -> str:
        if isinstance(expr, A.Literal):
            val = expr.value
            if isinstance(val, bool):
                return "1" if val else "0"
            if isinstance(val, float):
                return str(int(round(val * 100_000_000)))
            return str(val)
        if isinstance(expr, A.Var):
            if expr.name in env:
                return env[expr.name]
            tag = self._enum_tags().get(expr.name)
            if tag is not None:
                return str(tag)
            return _glsl_name(expr.name)
        if isinstance(expr, A.TableGet):
            return f"{expr.table}_get_{expr.column}(lane, {self._expr(expr.key, env)})"
        if isinstance(expr, A.TableExists):
            return f"{expr.table}_exists(lane, {self._expr(expr.key, env)})"
        if isinstance(expr, A.TableAccess):
            return f"{expr.table}_get_{expr.column}(lane, {self._expr(expr.key, env)})"
        if isinstance(expr, A.Select):
            return f"(({self._expr(expr.cond, env)}) ? ({self._expr(expr.a, env)}) : ({self._expr(expr.b, env)}))"
        if isinstance(expr, A.Unary):
            if expr.op == "not":
                return f"(!({self._expr(expr.operand, env)}))"
            return f"(-{self._expr(expr.operand, env)})"
        if isinstance(expr, A.Binary):
            a = self._expr(expr.left, env)
            b = self._expr(expr.right, env)
            sym = {"add": "+", "sub": "-", "mul": "*", "div": "/", "rem": "%",
                   "eq": "==", "ne": "!=", "lt": "<", "le": "<=", "gt": ">", "ge": ">=",
                   "and": "&&", "or": "||", "xor": "!="}.get(expr.op)
            if sym:
                return f"(({a}) {sym} ({b}))"
            if expr.op == "min":
                return f"(({a}) < ({b}) ? ({a}) : ({b}))"
            if expr.op == "max":
                return f"(({a}) > ({b}) ? ({a}) : ({b}))"
        return "0"

    # --- alloc helpers (emitted per table) ------------------------------
    def _emit_alloc_helpers(self) -> None:
        for tname, tinfo in self.prog.tables.items():
            up = tname.upper()
            kb = tinfo.layout.key_bits
            cols = ", ".join(f"{_glsl_type(c.type)} {c.name}" for c in tinfo.columns.values())
            self.w(f"uint64_t {tname}_alloc(int lane, {cols}) {{")
            self.w(f"    int slot = FUZZ_CAP;")
            self.w(f"    for (int s = 0; s < FUZZ_CAP; ++s) {{")
            self.w(f"        if ({tname}_occ[s * 32 + lane] == 0u) {{ slot = s; break; }}")
            self.w(f"    }}")
            self.w(f"    if (slot == FUZZ_CAP) {{ return 0ul; }}")
            self.w(f"    {tname}_occ[slot * 32 + lane] = 1u;")
            self.w(f"    {tname}_gen[slot * 32 + lane] += 1u;")
            for c in tinfo.columns.values():
                self.w(f"    {tname}_{c.name}[slot * 32 + lane] = {c.name};")
                if c.tracked_sum:
                    self.w(f"    {tname}_agg_{c.name}[lane] += {c.name};")
            self.w(f"    return (uint64_t({tname}_gen[slot * 32 + lane]) << {kb}) | uint64_t(slot);")
            self.w(f"}}")
            self.w()

    # --- invariants ----------------------------------------------------
    def _emit_invariants(self) -> None:
        self.w("bool vera_check_invariants(int lane) {")
        for inv in self.prog.invariants.values():
            if inv.quant_table is None:
                continue
            tinfo = self.prog.tables[inv.quant_table]
            self.w(f"    // invariant {inv.name}")
            for c in tinfo.columns.values():
                pass
            # generic: evaluate the quantified predicate per occupied slot
            self.w(f"    for (int s = 0; s < FUZZ_CAP; ++s) {{")
            self.w(f"        if ({inv.quant_table}_occ[s * 32 + lane] != 0u) {{")
            env = {inv.quant_var: f"(uint64_t({inv.quant_table}_gen[s * 32 + lane]) << {tinfo.layout.key_bits}) | uint64_t(s)"}
            # only column-comparison invariants are emitted generically here
            if self._is_simple_column_invariant(inv):
                self.w(f"            if (!({self._expr(inv.expr, env)})) {{ return false; }}")
            self.w(f"        }}")
            self.w(f"    }}")
        self.w("    return true;")
        self.w("}")
        self.w()

    def _is_simple_column_invariant(self, inv) -> bool:
        return isinstance(inv.expr, A.Binary) and inv.expr.op in ("ge", "le", "gt", "lt", "eq", "ne")

    # --- main ----------------------------------------------------------
    def _emit_main(self) -> None:
        self.w("void vera_init_sandbox(int lane) {")
        for tname, tinfo in self.prog.tables.items():
            for s in range(self.fuzz_cap):
                self.w(f"    {tname}_occ[{s} * 32 + lane] = 0u;")
            for c in tinfo.columns.values():
                init = "0" if c.type.kind != "bytes32" else "0ul"
                for s in range(self.fuzz_cap):
                    self.w(f"    {tname}_{c.name}[{s} * 32 + lane] = {init};")
        # seed two accounts
        if "Account" in self.prog.tables:
            self.w("    Account_occ[0 * 32 + lane] = 1u; Account_gen[0 * 32 + lane] = 1u;")
            self.w("    Account_balance[0 * 32 + lane] = 800000000;")
            self.w("    Account_occ[1 * 32 + lane] = 1u; Account_gen[1 * 32 + lane] = 1u;")
            self.w("    Account_balance[1 * 32 + lane] = 700000000;")
            self.w("    Account_agg_balance[lane] = 1500000000;")
        self.w("}")
        self.w()
        self.w("void main() {")
        self.w("    int lane = int(gl_LocalInvocationID.x);")
        self.w("    uint gid = gl_WorkGroupID.x * 32u + uint(lane);")
        self.w("    vera_rng_seed(0x9E3779B97F4A7C15ul * (uint64_t(gid) + 1ul));")
        self.w("    vera_init_sandbox(lane);")
        self.w("    uint steps = 0u;")
        self.w("    for (int step = 0; step < DEPTH; ++step) {")
        self.w("        uint pick = uint(vera_rng_next() % uint64_t(3u));")
        if "transfer" in self.prog.transitions:
            self.w("        if (pick == 0u) {")
            self.w("            uint64_t from = (1ul << KEY_BITS_ACCOUNT) | (vera_rng_next() % 2ul);")
            self.w("            uint64_t to = (1ul << KEY_BITS_ACCOUNT) | (vera_rng_next() % 2ul);")
            self.w("            int64_t amount = int64_t(vera_rng_next() % uint64_t(1000000000));")
            self.w("            if (transition_transfer(lane, from, to, amount)) { atomicAdd(committed, 1u); }")
            self.w("        } else if (pick == 1u) {")
            self.w("            uint64_t acct = (1ul << KEY_BITS_ACCOUNT) | (vera_rng_next() % 2ul);")
            self.w("            if (transition_freeze(lane, acct)) { atomicAdd(committed, 1u); }")
            self.w("        } else {")
            self.w("            uint64_t buyer = (1ul << KEY_BITS_ACCOUNT) | (vera_rng_next() % 2ul);")
            self.w("            int64_t amount = int64_t(vera_rng_next() % uint64_t(100000000));")
            self.w("            if (transition_place_order(lane, buyer, amount)) { atomicAdd(committed, 1u); }")
            self.w("        }")
        self.w("        steps++;")
        self.w("        if (!vera_check_invariants(lane)) { atomicAdd(violations, 1u); break; }")
        self.w("    }")
        self.w("}")


def generate_glsl(prog: Program, fuzz_cap: int = 16, depth: int = 64) -> str:
    gen = GlslGenerator(prog, fuzz_cap, depth)
    gen.w("// Generated by VERA v1.1.0 -- OpenGL 4.6 fuzzing furnace (Target B).")
    gen.w("#version 460 core")
    gen.w("#extension GL_ARB_gpu_shader_int64 : enable")
    gen.w()
    gen.w("layout(local_size_x = 32) in;")
    gen.w()
    gen.w("layout(std430, binding = 0) buffer Output {")
    gen.w("    uint violations;")
    gen.w("    uint committed;")
    gen.w("    uint pad0;")
    gen.w("    uint pad1;")
    gen.w("};")
    gen.w()
    for tname, tinfo in prog.tables.items():
        up = tname.upper()
        gen.w(f"const int CAP_{up} = {tinfo.layout.capacity};")
        gen.w(f"const int KEY_BITS_{up} = {tinfo.layout.key_bits};")
        gen.w(f"const int GEN_BITS_{up} = {tinfo.layout.generation_bits};")
    gen.w(f"const int FUZZ_CAP = {fuzz_cap};")
    gen.w(f"const int DEPTH = {depth};")
    gen.w()
    for tname, tinfo in prog.tables.items():
        for c in tinfo.columns.values():
            gen.w(f"shared {_glsl_type(c.type)} {tname}_{c.name}[FUZZ_CAP * 32];")
        gen.w(f"shared uint {tname}_occ[FUZZ_CAP * 32];")
        gen.w(f"shared uint {tname}_gen[FUZZ_CAP * 32];")
        for c in tinfo.columns.values():
            if c.tracked_sum:
                gen.w(f"shared {_glsl_type(c.type)} {tname}_agg_{c.name}[32];")
    gen.w()
    gen._emit_prng()
    gen._emit_helpers()
    gen._emit_alloc_helpers()
    for tname, tinfo in prog.tables.items():
        gen._emit_table_helpers(tname, tinfo)
    for tname in prog.transitions:
        gen._emit_transition(tname)
    gen._emit_invariants()
    gen._emit_main()
    return "\n".join(gen.lines) + "\n"
